import json
from typing import Any

from packages.ai_engine.prompts.generation import CODE_PROMPT, SYSTEM_PROMPT


class CoderAgent:
    name = "coder"

    def __init__(self, provider: Any | None = None) -> None:
        self.provider = provider

    def run(self, state: dict[str, Any]) -> dict[str, Any]:
        if self.provider is None or getattr(self.provider, "name", "local") == "local":
            project = state["project_name"]
            return {
                "files": [
                    {"path": "README.md", "content": f"# {project}\n\nGenerated by AI Application Factory.\n"},
                    {"path": "apps/api/main.py", "content": "from fastapi import FastAPI\n\napp = FastAPI()\n\n@app.get('/health')\ndef health():\n    return {'status': 'ok'}\n"},
                ],
                "code_status": "complete",
            }

        architecture = json.dumps(state.get("architecture", {}), indent=2)
        tasks = json.dumps(state.get("tasks", []), indent=2)
        prompt = (
            f"Project: {state['project_name']}\n"
            f"Requirements: {json.dumps(state.get('requirements', []))}\n"
            f"Architecture:\n{architecture}\n"
            f"Tasks:\n{tasks}\n\n{CODE_PROMPT}"
        )
        raw = self.provider.generate(SYSTEM_PROMPT, prompt)
        try:
            result = json.loads(raw)
            files = result.get("files", [])
            if not isinstance(files, list):
                raise ValueError("files must be a list")
            for item in files:
                if not isinstance(item, dict) or not isinstance(item.get("path"), str) or not isinstance(item.get("content"), str):
                    raise ValueError("each generated file requires path and content")
            return {"files": files, "code_status": "complete"}
        except (json.JSONDecodeError, ValueError) as exc:
            return {"files": [], "code_status": "failed", "code_error": str(exc)}
